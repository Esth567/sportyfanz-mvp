BEGIN;

-- ==========================================
-- 1. GUEST POLL VOTES
-- ==========================================

CREATE TABLE IF NOT EXISTS public.guest_poll_votes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "pollId" INTEGER NOT NULL
    REFERENCES public.polls(id),
  "optionId" INTEGER NOT NULL
    REFERENCES public.poll_options(id),
  "guestTokenHash" TEXT NOT NULL,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS
  guest_poll_votes_poll_guest_unique
ON public.guest_poll_votes ("pollId", "guestTokenHash");

CREATE INDEX IF NOT EXISTS
  guest_poll_votes_option_idx
ON public.guest_poll_votes ("optionId");

-- ==========================================
-- 2. TRIVIA QUIZZES
-- ==========================================

CREATE TABLE IF NOT EXISTS public.trivia_quizzes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  description TEXT,
  "coverImageUrl" TEXT,
  status TEXT NOT NULL DEFAULT 'DRAFT',
  "startsAt" TIMESTAMPTZ,
  "endsAt" TIMESTAMPTZ,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS
  trivia_quizzes_status_idx
ON public.trivia_quizzes (status);

-- ==========================================
-- 3. EXTEND EXISTING TRIVIA QUESTIONS
-- ==========================================

ALTER TABLE public.trivia_questions
  ADD COLUMN IF NOT EXISTS "quizId" INTEGER,
  ADD COLUMN IF NOT EXISTS "questionOrder" INTEGER NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS "imageUrl" TEXT,
  ADD COLUMN IF NOT EXISTS explanation TEXT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conname = 'trivia_questions_quizid_fkey'
      AND conrelid = 'public.trivia_questions'::regclass
  ) THEN
    ALTER TABLE public.trivia_questions
      ADD CONSTRAINT trivia_questions_quizId_fkey
      FOREIGN KEY ("quizId")
      REFERENCES public.trivia_quizzes(id);
  END IF;
END
$$;

CREATE INDEX IF NOT EXISTS
  trivia_questions_quiz_order_idx
ON public.trivia_questions ("quizId", "questionOrder");

COMMIT;
