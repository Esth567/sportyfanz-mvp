-- SportyFanz email verification migration
-- Review and back up the database before execution.
-- This migration must run before deploying the new backend.

BEGIN;


-- Add registration fields.
ALTER TABLE public.users
  ADD COLUMN IF NOT EXISTS "firstName" TEXT,
  ADD COLUMN IF NOT EXISTS "lastName" TEXT,
  ADD COLUMN IF NOT EXISTS "whatsappNumber" TEXT,
  ADD COLUMN IF NOT EXISTS country TEXT,
  ADD COLUMN IF NOT EXISTS state TEXT,
  ADD COLUMN IF NOT EXISTS sex TEXT,
  ADD COLUMN IF NOT EXISTS "dateOfBirth" TEXT;

-- Store hashed email verification codes.
CREATE TABLE IF NOT EXISTS public.email_verification_codes (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId" INTEGER NOT NULL UNIQUE,
  "codeHash" TEXT NOT NULL,
  "expiresAt" TIMESTAMPTZ NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Support guest messages in Fan Rooms.
ALTER TABLE public.fan_room_messages
  ADD COLUMN IF NOT EXISTS "guestId" TEXT,
  ADD COLUMN IF NOT EXISTS "guestName" TEXT;

-- Guest messages have no registered userId.
ALTER TABLE public.fan_room_messages
  ALTER COLUMN "userId" DROP NOT NULL;

CREATE INDEX IF NOT EXISTS fan_room_messages_guestId_idx
  ON public.fan_room_messages ("guestId");

COMMIT;
